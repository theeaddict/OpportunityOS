-- 028_admin_users.sql
--
-- STAGE 7: A SEPARATE, platform-administrator identity for the /admin/*
-- control room. The whole-system admin no longer reuses a tenant `users` row
-- with an is_superadmin flag: it has its own table, its own credentials, its
-- own session cookie (oos_admin_session) and its own login flow, so the
-- control room is fully decoupled from OpportunityOS user accounts.
--
-- admin_sessions mirrors sessions (token / FK / expiry). audit_logs gains
-- admin_user_id so admin-originated actions (suspend/plan/delete...) are
-- attributed to the administrator, not to any tenant account member.

CREATE TABLE IF NOT EXISTS admin_users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,   -- same scrypt format as users.password_hash
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_admin_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS admin_sessions (
  token         CHAR(64) PRIMARY KEY,
  admin_user_id BIGINT NOT NULL,
  expires_at    TIMESTAMP NOT NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_admin_sessions_admin FOREIGN KEY (admin_user_id) REFERENCES admin_users(id) ON DELETE CASCADE
);

-- Admin-originated audit rows reference the admin identity, not a tenant user.
ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS admin_user_id BIGINT NULL;