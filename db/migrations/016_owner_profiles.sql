-- 016_owner_profiles.sql
-- Business Owner Mode: the owner's plain-language profile + the strategy the
-- system derives from their onboarding answers.
--
-- This is deliberately separate from user_capabilities (the software-provider
-- profile). A business owner is not assumed to understand AI agents, prompts,
-- APIs, evidence models or scoring — they answer four plain questions and the
-- system builds the opportunity-finding strategy for them.

CREATE TABLE IF NOT EXISTS owner_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  business_name VARCHAR(200) NOT NULL,
  sell_what VARCHAR(500) NULL,
  location VARCHAR(200) NULL,
  ideal_customers VARCHAR(2000) NULL,
  goals JSONB NULL,
  strategy JSONB NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_owner_user UNIQUE (user_id)
);