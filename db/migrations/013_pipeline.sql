-- 013_pipeline.sql — Full opportunity pipeline
-- New 11-stage status flow, project value, probability, weighted pipeline,
-- days-in-stage tracking, notes, and activity_log for the timeline.

-- 1. Widen the status column so we can safely swap the allowed value set.
ALTER TABLE opportunities
  DROP CONSTRAINT chk_opps_status;
ALTER TABLE opportunities
  ALTER COLUMN status TYPE VARCHAR(40);

-- 2. Map old statuses to new ones.
UPDATE opportunities SET status = 'researching' WHERE status = 'analyzing';
UPDATE opportunities SET status = 'contacted'   WHERE status = 'outreach_sent';
UPDATE opportunities SET status = 'replied'     WHERE status = 'in_conversation';
UPDATE opportunities SET status = 'proposal'    WHERE status = 'proposal_sent';
UPDATE opportunities SET status = 'not_a_fit'   WHERE status = 'archived';

-- 3. Re-apply the new constraint.
ALTER TABLE opportunities
  ADD CONSTRAINT chk_opps_status CHECK (status IN (
    'new','researching','qualified','contacted','replied',
    'demo','proposal','negotiation','won','lost','not_a_fit'
  ));

-- 4. Pipeline tracking columns on opportunities.
ALTER TABLE opportunities
  ADD COLUMN project_value     DECIMAL(14,2) NULL,
  ADD COLUMN project_currency  CHAR(3) NULL,
  ADD COLUMN probability       DECIMAL(5,2) NULL,
  ADD COLUMN weighted_pipeline DECIMAL(14,2) NULL,
  ADD COLUMN days_in_stage     SMALLINT NULL,
  ADD COLUMN stage_entered_at  TIMESTAMP NULL,
  ADD COLUMN notes             TEXT NULL;

-- 5. Set default probabilities based on current status.
UPDATE opportunities SET probability = 10  WHERE status = 'new';
UPDATE opportunities SET probability = 20  WHERE status = 'researching';
UPDATE opportunities SET probability = 30  WHERE status = 'qualified';
UPDATE opportunities SET probability = 40  WHERE status = 'contacted';
UPDATE opportunities SET probability = 50  WHERE status = 'replied';
UPDATE opportunities SET probability = 60  WHERE status = 'demo';
UPDATE opportunities SET probability = 70  WHERE status = 'proposal';
UPDATE opportunities SET probability = 80  WHERE status = 'negotiation';
UPDATE opportunities SET probability = 100 WHERE status = 'won';
UPDATE opportunities SET probability = 0   WHERE status = 'lost';
UPDATE opportunities SET probability = 0   WHERE status = 'not_a_fit';

-- Backfill stage_entered_at from the most recent pipeline event.
UPDATE opportunities o
  SET stage_entered_at = pe.created_at
  FROM pipeline_events pe
  WHERE pe.opportunity_id = o.id
    AND pe.id = (
      SELECT pe2.id FROM pipeline_events pe2
      WHERE pe2.opportunity_id = o.id
      ORDER BY pe2.created_at DESC, pe2.id DESC LIMIT 1
    );

-- Compute days_in_stage for all rows.
UPDATE opportunities
  SET days_in_stage = GREATEST(0, (CURRENT_DATE - stage_entered_at::date))
  WHERE stage_entered_at IS NOT NULL;

-- 6. Activity log — the comprehensive timeline (not just status changes).
CREATE TABLE activity_log (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id BIGINT NOT NULL,
  activity_type  VARCHAR(60) NOT NULL,   -- status_change, note, outreach, demo, analysis, pipeline_edit, ...
  title          VARCHAR(200) NULL,
  detail         TEXT NULL,
  metadata       JSONB NULL,
  actor_user_id  BIGINT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_activity_opp FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE CASCADE,
  CONSTRAINT fk_activity_user FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_activity_opp ON activity_log (opportunity_id, created_at);

-- 7. Seed activity_log from existing pipeline_events for backward compatibility.
INSERT INTO activity_log (opportunity_id, activity_type, title, detail, actor_user_id, created_at)
SELECT
  pe.opportunity_id,
  'status_change',
  CONCAT(COALESCE(pe.from_status, 'new'), ' → ', pe.to_status),
  pe.notes,
  pe.actor_user_id,
  pe.created_at
FROM pipeline_events pe;