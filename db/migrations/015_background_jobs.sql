-- 015_background_jobs.sql
-- Unified background job queue (DB-backed MVP).
--
-- Replaceability: the queue interface in lib/jobs/queue.js mirrors BullMQ's
-- Job/Queue API (enqueue ≈ Queue.add, reportProgress ≈ job.updateProgress,
-- complete ≈ job.moveToCompleted, fail ≈ job.moveToFailed, retry ≈ job.retry,
-- cancel ≈ safe removal), so the storage engine can be swapped for
-- Redis/BullMQ later without touching handlers or UI.
--
-- Lifecycle: queued -> running -> completed | failed | cancelled
--   - attempts increments on each claim; a failure requeues while
--     attempts < max_attempts, otherwise the job is failed (terminal).
--   - cancel_requested lets the caller stop a running job at a safe point;
--     queued jobs are cancelled immediately on request.
--   - progress/stage only ever reflect real underlying work; the worker marks
--     a job complete ONLY when its handler has fully finished.

CREATE TABLE IF NOT EXISTS background_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type VARCHAR(40) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'queued'
         CONSTRAINT chk_bgjobs_status CHECK (status IN ('queued','running','completed','failed','cancelled')),
  attempts SMALLINT NOT NULL DEFAULT 0,
  max_attempts SMALLINT NOT NULL DEFAULT 3,
  payload JSONB NULL,
  result JSONB NULL,
  error TEXT NULL,
  progress SMALLINT NOT NULL DEFAULT 0,
  stage VARCHAR(60) NULL,
  dedup_key CHAR(64) NULL,
  cancel_requested SMALLINT NOT NULL DEFAULT 0,
  created_by BIGINT NULL,
  started_at TIMESTAMP NULL,
  completed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_bgjobs_status_type ON background_jobs (status, type);
CREATE INDEX idx_bgjobs_dedup ON background_jobs (type, dedup_key, status);
CREATE INDEX idx_bgjobs_created ON background_jobs (created_at);