-- 030_api_keys_and_customer_care.sql
-- STAGE 10: platform-issued API keys (per-account credentials for the ingest
-- webhook) and customer-care contacts (the platform's outreach records per
-- account). Both are control-room managed (audited) and gated by
-- requireSuperadmin().

CREATE TABLE IF NOT EXISTS api_keys (
  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id    BIGINT       NOT NULL,
  name          VARCHAR(80)  NOT NULL,
  key_prefix    VARCHAR(24)  NOT NULL,
  key_hash      CHAR(64)     NOT NULL,
  status        VARCHAR(10)  NOT NULL DEFAULT 'active'
                 CONSTRAINT chk_api_keys_status CHECK (status IN ('active','revoked')),
  rate_limit_hour INTEGER    NULL,
  last_used_at  TIMESTAMP    NULL,
  created_by    BIGINT       NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_api_keys_hash UNIQUE (key_hash),
  CONSTRAINT uq_api_keys_account_name UNIQUE (account_id, name),
  CONSTRAINT chk_api_keys_account CHECK (account_id > 0)
);

CREATE INDEX idx_api_keys_account ON api_keys (account_id);

CREATE TABLE IF NOT EXISTS customer_care_contacts (
  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id    BIGINT       NOT NULL,
  name          VARCHAR(120) NOT NULL,
  role          VARCHAR(80)  NULL,
  email         VARCHAR(255) NULL,
  phone         VARCHAR(40)  NULL,
  notes         TEXT         NULL,
  reach_out     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_by    BIGINT       NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_care_account CHECK (account_id > 0)
);

CREATE INDEX idx_care_account ON customer_care_contacts (account_id);
CREATE INDEX idx_care_reach_out ON customer_care_contacts (reach_out);