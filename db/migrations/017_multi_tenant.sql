ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name;

-- ---------------------------------------------------------------------------
-- 2. users: account membership + SaaS roles
-- ---------------------------------------------------------------------------

-- Map the legacy single-tenant roles ('admin'/'analyst') onto the SaaS model.
-- Swap the role CHECK constraint to the SaaS set before re-mapping values.
ALTER TABLE users
  ADD COLUMN account_id BIGINT NULL,
  DROP CONSTRAINT chk_users_role;
ALTER TABLE users
  ALTER COLUMN role TYPE VARCHAR(10),
  ADD CONSTRAINT chk_users_role CHECK (role IN ('owner','admin','member')),
  ADD CONSTRAINT fk_users_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE SET NULL;

CREATE INDEX idx_users_account ON users (account_id);

UPDATE users SET role = 'owner' WHERE role = 'admin';
UPDATE users SET role = 'member' WHERE role = 'analyst';
UPDATE users SET account_id = 1 WHERE id = 1;

