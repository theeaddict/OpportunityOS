-- 017_multi_tenant.sql
-- Multi-tenant SaaS preparation.
--
-- Adds account isolation: every tenant-owned table gains account_id and is
-- backfilled to the seed "internal" account (id=1). Roles move to the SaaS
-- model OWNER / ADMIN / MEMBER. Subscription-ready structures (billing_plans,
-- accounts.plan_code, account_usage) are created WITHOUT any payment handling.

-- ---------------------------------------------------------------------------
-- 1. billing plans + accounts + usage
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS billing_plans (
  code VARCHAR(40) NOT NULL,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(300) NULL,
  -- Monthly limits; NULL means unlimited. Billing is not implemented yet —
  -- these rows exist so usage/limits can be surfaced and enforced later.
  limit_researches INTEGER NULL,
  limit_opportunities INTEGER NULL,
  limit_ai_analyses INTEGER NULL,
  limit_demo_generations INTEGER NULL,
  limit_users INTEGER NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (code)
);

INSERT INTO billing_plans (code, name, description, limit_researches, limit_opportunities, limit_ai_analyses, limit_demo_generations, limit_users) VALUES
  ('internal', 'Internal workspace', 'Single-user internal system — unlimited', NULL, NULL, NULL, NULL, NULL),
  ('free',      'Free',             'Starter limits for a new workspace',        50, 200, 50, 20, 5),
  ('pro',       'Pro',              'Higher limits',                           500, 2000, 500, 200, 25)
ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description;

CREATE TABLE IF NOT EXISTS accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  plan_code VARCHAR(40) NOT NULL DEFAULT 'free'
           CONSTRAINT chk_accounts_plan CHECK (plan_code IN ('internal','free','pro')),
  status VARCHAR(10) NOT NULL DEFAULT 'active'
         CONSTRAINT chk_accounts_status CHECK (status IN ('active','suspended')),
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_accounts_plan FOREIGN KEY (plan_code) REFERENCES billing_plans (code)
);

CREATE INDEX idx_accounts_plan ON accounts (plan_code);

CREATE TABLE IF NOT EXISTS account_usage (
  account_id BIGINT NOT NULL,
  period CHAR(7) NOT NULL,
  researches_used INTEGER NOT NULL DEFAULT 0,
  opportunities_used INTEGER NOT NULL DEFAULT 0,
  ai_analyses_used INTEGER NOT NULL DEFAULT 0,
  demo_generations_used INTEGER NOT NULL DEFAULT 0,
  users_used INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (account_id, period),
  CONSTRAINT fk_account_usage_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE
);

