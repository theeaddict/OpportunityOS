-- 019_discover_schedules.sql
-- Per-account recurring discovery ("watch") schedules. The job scheduler that
-- runs inside the background worker ticks due schedules and enqueues a
-- DISCOVERY job for each, so opportunities keep arriving without a manual run.

CREATE TABLE IF NOT EXISTS discover_schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL DEFAULT 1,
  name VARCHAR(160) NOT NULL,
  provider VARCHAR(40) NOT NULL DEFAULT 'demo',
  filters_json JSONB NULL,
  interval_minutes INTEGER NOT NULL DEFAULT 60,
  next_run_at TIMESTAMP NULL,
  last_run_at TIMESTAMP NULL,
  enabled SMALLINT NOT NULL DEFAULT 1,
  created_by BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_sched_account_name UNIQUE (account_id, name)
);

CREATE INDEX idx_sched_due ON discover_schedules (enabled, next_run_at);
CREATE INDEX idx_sched_account ON discover_schedules (account_id);

-- Backing indexes for the ongoing job queue (dispatch/DISCOVERY lookups).
CREATE INDEX idx_bgj_type_status ON background_jobs (type, status);
CREATE INDEX idx_bgj_account_type ON background_jobs (account_id, type, created_at);