-- 014_capabilities.sql — "My Capabilities": the user's own business profile.
-- The opportunity engine uses this to filter recommendations (only build what
-- the user actually ships) and to flag detected opportunities the user cannot
-- serve as NOT_A_SERVICE_FIT.

-- 1. New terminal status: detected, but no enabled capability can serve it.
ALTER TABLE opportunities
  DROP CONSTRAINT chk_opps_status;
ALTER TABLE opportunities
  ADD CONSTRAINT chk_opps_status CHECK (status IN (
    'new','researching','qualified','contacted','replied',
    'demo','proposal','negotiation','won','lost','not_a_fit','not_a_service_fit'
  ));

-- 2. The user's own business / capability profile (one row per user).
CREATE TABLE IF NOT EXISTS user_capabilities (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                   BIGINT NOT NULL,
  business_name             VARCHAR(160) NOT NULL DEFAULT '',
  location                  VARCHAR(160) NULL,
  services                  TEXT NULL,
  industries_served         JSONB NULL,
  technologies              JSONB NULL,
  solution_types            JSONB NULL,
  enabled_solutions         JSONB NULL,
  min_project_value         DECIMAL(14,2) NULL,
  max_project_value         DECIMAL(14,2) NULL,
  preferred_industries      JSONB NULL,
  preferred_locations       JSONB NULL,
  preferred_problem_categories JSONB NULL,
  preferred_client_size     VARCHAR(10) NULL
                            CONSTRAINT chk_capabilities_client_size CHECK (preferred_client_size IN
                              ('small','medium','large','enterprise')),
  updated_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_user_capabilities UNIQUE (user_id)
);