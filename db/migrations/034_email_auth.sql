-- 034_email_auth.sql — password reset + email verification.
--
-- Tokens are random 32-byte values emailed to the user; only their SHA-256
-- hash is stored, so a database read never yields a usable link.

ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP NULL;

-- Everyone who exists today predates verification. Treat them as verified so
-- turning REQUIRE_EMAIL_VERIFICATION on never locks out an existing user.
UPDATE users SET email_verified_at = COALESCE(created_at, CURRENT_TIMESTAMP) WHERE email_verified_at IS NULL;

CREATE TABLE IF NOT EXISTS auth_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  purpose    VARCHAR(20) NOT NULL
             CONSTRAINT chk_auth_tokens_purpose CHECK (purpose IN ('password_reset', 'email_verify')),
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  used_at    TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT uq_auth_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_auth_tokens_user ON auth_tokens (user_id, purpose);
